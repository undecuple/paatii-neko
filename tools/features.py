#!/usr/bin/env python3
"""Feature page: docs/features.tsv -> docs/FEATURES.md (public, generated; never hand-edited). After the Killzone 3
port's tools/features.py (same author, MIT), cut down to Toro's columns.

    python3 tools/features.py           # regenerate docs/FEATURES.md
    python3 tools/features.py --check   # exit 1 when docs/FEATURES.md is stale or a row is malformed

docs/features.tsv columns (tab-separated, header row first):
  kind      ps3: a feature of the PS3 game; port: something only the port adds
  area      section heading on the page
  feature   one line
  ps3       what the PS3 game does ("-" when there is nothing to say)
  status    works / partial / not yet / not yet verified / declined / not applicable
  evidence  what was run or seen, with its date; plain words, no internal run names

The internal chart against RPCS3 stays in docs/PARITY.md (tools/progress.py). Public wording goes through the gate.
"""
import csv
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "docs", "features.tsv")
OUT = os.path.join(ROOT, "docs", "FEATURES.md")
STATUSES = ("works", "partial", "not yet", "not yet verified", "declined", "not applicable")
# Port parity estimate, as on the Killzone 3 page: works 1, partial 1/2, not yet verified 1/4, not yet 0; declined and
# not applicable are left out.
SCORE = {"works": 1.0, "partial": 0.5, "not yet verified": 0.25, "not yet": 0.0}


def load():
    with open(SRC, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    bad = []
    for i, r in enumerate(rows, 2):
        if r.get("kind") not in ("ps3", "port"):
            bad.append(f"line {i}: kind {r.get('kind')!r}")
        if r.get("status") not in STATUSES:
            bad.append(f"line {i}: status {r.get('status')!r}")
        if any('"' in (v or "") for v in r.values()):
            bad.append(f"line {i}: straight double quote (GitHub's TSV view rejects it; use “ ”)")
        if not (r.get("feature") or "").strip() or not (r.get("evidence") or "").strip():
            bad.append(f"line {i}: empty feature or evidence")
    return rows, bad


def render(rows):
    ps3 = [r for r in rows if r["kind"] == "ps3"]
    port = [r for r in rows if r["kind"] == "port"]
    counted = [r for r in ps3 if r["status"] in SCORE]
    est = 100.0 * sum(SCORE[r["status"]] for r in counted) / len(counted) if counted else 0.0
    counts = ", ".join(f"{s} {sum(r['status'] == s for r in ps3)}" for s in STATUSES if any(r["status"] == s for r in ps3))
    L = ["<!-- Generated by tools/features.py from docs/features.tsv. Do not edit by hand. -->",
         "# Features: the PS3 game and the port", "",
         "One row per feature of the PS3 game, with what the port does today and what showed it. A second table lists "
         "what only the port adds. Status: works, partial, not yet, not yet verified.", "",
         f"PS3 features: {len(ps3)} ({counts}). Estimated parity: {est:.0f} % (an estimate: works counts 1, partial 1/2, "
         "not yet verified 1/4, not yet 0).", ""]
    areas = []
    for r in ps3:
        if r["area"] not in areas:
            areas.append(r["area"])
    for a in areas:
        L += [f"## {a}", "", "| Feature | PS3 | Port | Evidence |", "|---|---|---|---|"]
        for r in ps3:
            if r["area"] == a:
                L.append(f"| {r['feature']} | {r['ps3']} | **{r['status']}** | {r['evidence']} |")
        L.append("")
    if port:
        L += ["## Only in the port", "", "| Feature | Where it applies | Port | Evidence |", "|---|---|---|---|"]
        for r in port:
            L.append(f"| {r['feature']} | {r['ps3']} | **{r['status']}** | {r['evidence']} |")
        L.append("")
    return "\n".join(L)


def main():
    rows, bad = load()
    if bad:
        print("features.tsv: " + "; ".join(bad), file=sys.stderr)
        return 1
    text = render(rows)
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("docs/FEATURES.md is stale: run python3 tools/features.py", file=sys.stderr)
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"docs/FEATURES.md: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
