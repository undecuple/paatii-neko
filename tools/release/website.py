    inner = f"<span>{esc(top)}</span><b>{esc(bottom)}</b>"
    if href:
        return f'<li><a class="b88 {color}" href="{esc(href)}">{inner}</a></li>'
    return f'<li><span class="b88 {color}">{inner}</span></li>'


