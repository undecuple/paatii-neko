def lint(page):
    """Problems with what the page would load: scripts, and any resource from outside its own files."""
    problems = []
    if re.search(r"<script\b|\bon\w+\s*=|javascript:", page, re.I):
        problems.append("page contains a script or an event handler")
    for m in re.finditer(r"<(link|img|iframe|source|video|audio|embed|object)\b[^>]*?\b(?:href|src)=\"([^\"]+)\"", page, re.I):
        tag, url = m.group(1).lower(), m.group(2)
        if re.match(r"[a-z][a-z0-9+.-]*:|//", url, re.I):
            problems.append(f"<{tag}> loads {url} (only the page's own files are allowed)")
    for m in re.finditer(r"<meta\b[^>]*property=\"og:image\"[^>]*content=\"([^\"]*)\"", page, re.I):
        if not m.group(1).startswith(SITE_URL):
            problems.append(f"og:image {m.group(1)} is not under {SITE_URL}")
    if "Content-Security-Policy" not in page:
        problems.append("page has no Content-Security-Policy")
    for m in FORBIDDEN.finditer(page):
        problems.append(f"page contains {m.group(0)!r}")
    if "prefers-color-scheme" in page:
        problems.append("page mentions prefers-color-scheme (paper only)")
    if len(page.encode("utf-8")) > PAGE_BUDGET:
        problems.append("page is over 1 MB")
    return problems


def css_problems(css):
    """The stylesheet: tokens equal TOKENS, paper only, nothing loaded but its own fonts and data: URIs."""
    problems = []
    if "prefers-color-scheme" in css:
        problems.append("style.css has prefers-color-scheme (paper only)")
    if re.search(r"@import", css):
        problems.append("style.css has @import")
    for m in re.finditer(r"url\(\s*[\"']?([^\"')]*)", re.sub(r"url\(\s*([\"'])data:.*?\1\s*\)", "url(data:)", css)):
        u = m.group(1)
        if not (u.startswith("data:") or re.fullmatch(r"fonts/[\w.-]+\.woff2", u)):
            problems.append(f"style.css loads {u!r} (only fonts/*.woff2 and data: URIs are allowed)")
    if FORBIDDEN.search(css):
        problems.append(f"style.css contains {FORBIDDEN.search(css).group(0)!r}")
    found = dict(re.findall(r"--([\w-]+):\s*(#[0-9a-fA-F]{6})\s*;", css))
    for k, v in TOKENS.items():
        if found.get(k, "").lower() != v:
            problems.append(f"style.css token --{k} is {found.get(k)!r}, the table says {v}")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 on any problem")
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[2]), help="repo root")
    ap.add_argument("-q", action="store_true", help="print only problems")
    a = ap.parse_args(argv)
    root = pathlib.Path(a.root)
    problems = contrast_problems()
    try:
        page = render(root, problems)
    except (ValueError, OSError, KeyError) as e:
        print(f"website: {e!r}", file=sys.stderr)
        return 1
    problems += lint(page)
    if (root / CSS).is_file():
        problems += css_problems((root / CSS).read_text(encoding="utf-8"))
    if sum(1 for sid in SECTION_IDS if f'id="{sid}"' in page) != len(SECTION_IDS):
        problems.append("a section of the plan is missing")
    if re.search(r"<img\b(?![^>]*\balt=\"[^\"]+\")", page):
        problems.append("an image has no alt text")
    total = sum((root / FONT_DIR / f).stat().st_size for f in FONT_FILES if (root / FONT_DIR / f).is_file())
    for f in FONT_FILES if a.check else ():     # the fonts are made from the page, so generating comes first
        p = root / FONT_DIR / f
        if not p.is_file() or p.read_bytes()[:4] != b"wOF2":
            problems.append(f"{FONT_DIR}/{f} missing or not a woff2 file (run tools/release/site_fonts.py)")
    if total > FONT_BUDGET:
        problems.append(f"font files total {total} bytes, over {FONT_BUDGET}")
    out = root / PAGE
    if a.check:
        if not out.exists():
            problems.append(f"{PAGE} missing (run tools/release/website.py)")
        elif out.read_text(encoding="utf-8") != page:
            problems.append(f"{PAGE} is stale (run tools/release/website.py)")
    if problems:
        print("website: problems:", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        return 1
    if not a.check:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page, encoding="utf-8")
    if not a.q:
        print(f"website: {'OK' if a.check else PAGE} ({len(page)} bytes, fonts {total} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
